#!/usr/bin/env node
// Generates TypeScript interfaces from the units programs' Anchor IDLs, one namespace per program,
// into src/hookwars/idl-types.gen.ts. Field names are camelCase (what IdlCoder decodes to). Run
// after copying fresh IDLs into ../idl/: `node scripts/gen-idl-types.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const idlDir = join(here, '..', 'idl');
const out = join(here, '..', 'src', 'hookwars', 'idl-types.gen.ts');

const PROGRAMS = [
  ['Token', 'bordrless_token'],
  ['Armory', 'hookwars_armory'],
  ['Items', 'hookwars_items'],
  ['War', 'hookwars_war'],
  ['Kit', 'bordrless_kit'],
  ['Companion', 'bordrless_companion'],
  ['Launch', 'bordrless_launch'],
  ['Swap', 'bordrless_swap'],
  ['Agents', 'hookwars_agents'],
  ['Market', 'hookwars_market'],
  ['Social', 'hookwars_social'],
  // Changed by Hookwars (explorer v2): the economy programs (11).
  ['Craft', 'hookwars_craft'],
  ['Book', 'hookwars_book'],
];

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

function ts(t) {
  if (typeof t === 'string') {
    if (['u8', 'i8', 'u16', 'i16', 'u32', 'i32', 'f32', 'f64'].includes(t)) return 'number';
    if (['u64', 'i64', 'u128', 'i128'].includes(t)) return 'bigint';
    if (t === 'bool') return 'boolean';
    if (t === 'pubkey') return 'PublicKey';
    if (t === 'string') return 'string';
    if (t === 'bytes') return 'Buffer';
    return 'unknown';
  }
  if (t.option) return `${ts(t.option)} | null`;
  if (t.coption) return `${ts(t.coption)} | null`;
  if (t.vec) return `(${ts(t.vec)})[]`;
  if (t.array) return t.array[0] === 'u8' ? 'Buffer' : `(${ts(t.array[0])})[]`;
  if (t.defined) return typeof t.defined === 'string' ? t.defined : t.defined.name;
  return 'unknown';
}

function fieldsTs(fields) {
  if (!fields || fields.length === 0) return '{}';
  if (typeof fields[0] === 'object' && 'name' in fields[0] && 'type' in fields[0]) {
    return `{ ${fields.map((f) => `${camel(f.name)}: ${ts(f.type)};`).join(' ')} }`;
  }
  // Tuple fields decode as '0', '1', ... (codec.ts `fieldsOf`).
  return `{ ${fields.map((t, i) => `'${i}': ${ts(t)};`).join(' ')} }`;
}

let src = `// Generated by scripts/gen-idl-types.mjs from app/packages/sdk/idl/*.json. Do not edit by hand.\n`;
src += `import type { PublicKey } from '@solana/web3.js';\n`;
for (const [ns, file] of PROGRAMS) {
  let idl;
  try { idl = JSON.parse(readFileSync(join(idlDir, `${file}.json`), 'utf8')); } catch { continue; }
  src += `\nexport namespace ${ns} {\n`;
  for (const t of idl.types ?? []) {
    const k = t.type.kind;
    if (k === 'struct') src += `  export interface ${t.name} ${fieldsTs(t.type.fields)}\n`;
    else if (k === 'type') src += `  export type ${t.name} = ${ts(t.type.alias)};\n`;
    else if (k === 'enum') {
      const unit = t.type.variants.every((v) => !v.fields || v.fields.length === 0);
      src += unit
        ? `  export type ${t.name} = ${t.type.variants.map((v) => `'${v.name}'`).join(' | ')};\n`
        : `  export type ${t.name} = ${t.type.variants.map((v) => `({ name: '${v.name}' } & ${fieldsTs(v.fields)})`).join(' | ')};\n`;
    }
  }
  src += `}\n`;
}
writeFileSync(out, src);
console.log(`wrote ${out}`);
